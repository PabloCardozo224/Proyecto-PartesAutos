drop database if exists Auto_partes;
create database Auto_partes;
use Auto_partes;

create table Marcas(
    id_marca int auto_increment,
    nombre varchar(50),
    primary key (id_marca)
);

create table Empleados(
    Id_Empleado int auto_increment,
    Nombre varchar(35),
    Apellido varchar(35),
    DNI int,
    Telefono varchar(15),
    Puesto varchar(30),
    Rol varchar(35),
    primary key (Id_Empleado)
);

create table Productos(
    Id_Producto int auto_increment,
    Nombre varchar(35),
    Descripcion varchar(50),
    Tipo_Parte varchar(100),
    Tamaño enum("Chico","Mediano","Grande"),
    Cantidad int,
    precio int,
    color varchar(25),
    Modelo varchar(40),
    id_marca int,
    Tipo_Vehiculo enum("moto","auto","camion"),
    primary key (Id_Producto),
    foreign key (id_marca) references Marcas(id_marca)
);

create table Pagos(
    Id_Pago int auto_increment,
    Metodo enum("Efectivo","Transferencia","Tarjeta de debito"),
    Monto float,
    Estado enum("Pendiente","Confirmado","Denegado"),
    primary key (Id_Pago)
);

create table Envios(
    ID_Envio int auto_increment,
    N_casa int,
    nombre_calle varchar(45),
    nombre_barrio varchar(45),
    nombre_provincia varchar(45),
    nombre_localidad varchar(45),
    primary key (ID_Envio)
);

create table Ventas(
    id_Ventas int auto_increment,
    Fecha_venta datetime,
    cantidad_productos int,
    Tipo_pedido varchar(30),
    Id_Producto int,
    id_Empleado int,
    ID_Envio int,
    Id_Pago int,
    primary key (id_Ventas),
    foreign key (Id_Producto) references Productos(Id_Producto),
    foreign key (id_Empleado) references Empleados(Id_Empleado),
    foreign key (ID_Envio) references Envios(ID_Envio),
    foreign key (Id_Pago) references Pagos(Id_Pago)
);

create table Clientes(
    Id_cliente int auto_increment,
    Nombre varchar(35),
    Apellido varchar(35),
    DNI int,
    Telefono varchar(15),
    Direccion varchar(45),
    id_Ventas int,
    primary key (Id_cliente),
    foreign key (id_Ventas) references Ventas(id_Ventas)
);

